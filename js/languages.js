var currentLanguage = DEFAULT_LANGUAGE;

// נקרא מיד כשההגדרות נטענות, לפני שהמסך כותב טקסט כלשהו
function setLanguage(language) {
    currentLanguage = LANGUAGES[language] ? language : DEFAULT_LANGUAGE;
    applyLanguage();
}

// t('pointsNow', { points: 12 }) מחליף את {points} בערך
function t(key, params = {}) {
    const entry = TEXTS[key];
    if (!entry) {
        return key;
    }
    const text = entry[currentLanguage] !== undefined ? entry[currentLanguage] : entry[DEFAULT_LANGUAGE];
    if (Array.isArray(text)) {
        return text;
    }
    return text.replace(/\{(\w+)\}/g, (match, name) => params[name] !== undefined ? params[name] : match);
}

// טקסט קבוע ב-HTML מסומן ב-data-t="key"
function applyLanguage() {
    document.querySelectorAll('[data-t]').forEach(element => {
        element.innerHTML = t(element.dataset.t);
    });
}
